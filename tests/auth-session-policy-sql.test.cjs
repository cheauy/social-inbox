/* eslint-disable @typescript-eslint/no-require-imports */
const assert = require("node:assert/strict");
const fs = require("node:fs");
const test = require("node:test");
const modulePath = process.env.TENH_AUTH_PGLITE_MODULE;

test("trusted session snapshots, staged enforcement, recovery isolation and durable rate limits", {
  skip: !modulePath && "Set TENH_AUTH_PGLITE_MODULE to an isolated PGlite installation.",
}, async () => {
  const { PGlite } = require(modulePath);
  const db = new PGlite();
  const user = "10000000-0000-4000-8000-000000000001";
  const other = "10000000-0000-4000-8000-000000000002";
  const sid = n => `20000000-0000-4000-8000-${String(n).padStart(12, "0")}`;
  const value = async (sql, params = []) => (await db.query(sql, params)).rows[0].value;
  const inspect = n => value("select public.tenh_inspect_session_policy($1,$2) value", [user, sid(n)]);
  const bind = (n, remember = false, kind = "normal") => value("select public.tenh_bind_session_policy($1,$2,$3,$4) value", [user, sid(n), remember, kind]);
  const add = (n, age = "0 seconds") => db.query("insert into auth.sessions values ($1,$2,clock_timestamp()-$3::interval,null)", [sid(n), user, age]);
  const claims = async (n, uid = user) => {
    await db.query("select set_config('request.jwt.claims',$1,false)", [JSON.stringify({ sub: uid, session_id: sid(n), role: "authenticated" })]);
  };
  try {
    await db.exec(`
      create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth; create schema storage; create schema realtime;
      create table auth.users(id uuid primary key,email_confirmed_at timestamptz,banned_until timestamptz,deleted_at timestamptz);
      insert into auth.users values('${user}',clock_timestamp(),null,null),('${other}',clock_timestamp(),null,null);
      create table auth.sessions(id uuid primary key,user_id uuid,created_at timestamptz,not_after timestamptz);
      create function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb$$;
      create function auth.uid() returns uuid language sql stable as $$select (auth.jwt()->>'sub')::uuid$$;
      grant usage on schema auth,public,storage,realtime to anon,authenticated,service_role;
      grant execute on function auth.jwt(),auth.uid() to anon,authenticated,service_role;
      create table public.documents(id int primary key,user_id uuid,secret text);
      insert into public.documents values(1,'${user}','own'),(2,'${other}','other');
      alter table public.documents enable row level security;
      create policy tenant on public.documents to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
      grant all on public.documents to authenticated,service_role;
      create table storage.buckets(id text,public boolean);
      create table storage.objects(id int,user_id uuid);
      insert into storage.objects values(1,'${user}');
      alter table storage.objects enable row level security;
      create policy own on storage.objects to authenticated using(user_id=auth.uid());
      grant select on storage.objects to authenticated,service_role;
      create table realtime.messages(id int);
      insert into realtime.messages values(1);
      alter table realtime.messages enable row level security;
      create policy join_channel on realtime.messages to authenticated using(true);
      grant select on realtime.messages to authenticated,service_role;
    `);
    await db.exec(fs.readFileSync("db/migrations/20261015120849_auth_session_policy.sql", "utf8"));
    await db.exec(fs.readFileSync("db/checks/auth_session_policy_preflight.sql", "utf8"));
    assert.equal((await value("select public.tenh_get_session_policy_settings() value")).remember_days, 30);
    await assert.rejects(db.query("select public.tenh_set_session_policy_settings(0,$1)", [user]), /1 to 90/);
    await add(1);
    const first = await bind(1);
    assert.equal(first.kind, "normal");
    assert.equal(Date.parse(first.expires_at) - Date.parse(first.authenticated_at), 86400000);
    await db.query("update auth.users set banned_until=clock_timestamp()+interval '1 day' where id=$1", [user]);
    assert.equal((await inspect(1)).status, "account-disabled");
    await claims(1); await db.exec("set role authenticated");
    assert.equal((await db.query("select * from public.documents")).rows.length, 0);
    await db.exec("reset role");
    await db.query("update auth.users set banned_until=null,deleted_at=clock_timestamp() where id=$1", [user]);
    assert.equal((await inspect(1)).status, "account-disabled");
    await db.query("update auth.users set deleted_at=null,email_confirmed_at=null where id=$1", [user]);
    assert.equal((await inspect(1)).status, "email-unverified");
    await db.query("update auth.users set email_confirmed_at=clock_timestamp() where id=$1", [user]);
    await db.query("update auth.users set banned_until=clock_timestamp()-interval '1 second' where id=$1", [user]);
    assert.equal((await inspect(1)).status, "allowed");
    await db.query("delete from auth.users where id=$1", [user]);
    assert.equal((await inspect(1)).status, "account-disabled");
    await db.query("insert into auth.users values($1,clock_timestamp(),null,null)", [user]);
    await add(10);
    await db.query("update auth.sessions set not_after=clock_timestamp()+interval '1 hour' where id=$1", [sid(10)]);
    const providerLimited = await bind(10, true);
    assert.ok(Date.parse(providerLimited.expires_at)-Date.parse(providerLimited.authenticated_at) < 3601000);
    await db.query("update auth.sessions set not_after=clock_timestamp()+interval '2 days' where id=$1", [sid(10)]);
    assert.equal(Date.parse((await bind(10,true)).expires_at),Date.parse(providerLimited.expires_at));
    await add(2);
    await db.exec("set timezone = 'America/New_York'");
    const remembered = await bind(2, true);
    assert.equal(Date.parse(remembered.expires_at) - Date.parse(remembered.authenticated_at), 30 * 86400000);
    await db.exec("set timezone = 'UTC'");
    await db.query("select public.tenh_set_session_policy_settings(90,$1)", [user]);
    assert.equal((await value("select count(*)::int value from tenh_auth_private.session_settings_audit")), 1);
    assert.equal((await value("select actor_user_id value from tenh_auth_private.session_settings_audit")), user);
    await db.exec("create function tenh_auth_private.reject_audit() returns trigger language plpgsql as $$begin raise exception 'audit unavailable'; end$$; create trigger reject_audit before insert on tenh_auth_private.session_settings_audit for each row execute function tenh_auth_private.reject_audit()");
    await assert.rejects(db.query("select public.tenh_set_session_policy_settings(10,$1)", [user]), /audit unavailable/);
    assert.equal((await value("select public.tenh_get_session_policy_settings() value")).remember_days, 90);
    await db.exec("drop trigger reject_audit on tenh_auth_private.session_settings_audit; drop function tenh_auth_private.reject_audit()");
    assert.equal(Date.parse((await bind(2, false)).expires_at), Date.parse(remembered.expires_at));
    assert.equal((await bind(2, false)).remembered, true);
    await assert.rejects(db.query("update tenh_auth_private.session_policies set expires_at=expires_at+interval '1 day'"), /immutable/);
    await add(3, "20 minutes");
    assert.equal((await bind(3, true)).status, "fresh-authentication-required");
    assert.equal((await value("select public.tenh_bind_session_policy($1,$2,true,'normal') value", [other, sid(1)])).status, "provider-session-missing");
    await claims(1);
    await db.exec("set role authenticated");
    assert.deepEqual((await db.query("select id from public.documents")).rows, [{ id: 1 }]);
    await assert.rejects(db.query("select public.tenh_bind_session_policy($1,$2,true,'normal')", [user, sid(1)]), /permission denied/);
    await assert.rejects(db.query("select public.tenh_inspect_session_policy($1,$2)", [user, sid(1)]), /permission denied/);
    await assert.rejects(db.query("select public.tenh_set_session_policy_settings(10,$1)", [user]), /permission denied/);
    await assert.rejects(db.query("select public.tenh_claim_recovery_session($1,$2)", [user, sid(1)]), /permission denied/);
    await db.exec("reset role");
    await db.query("select set_config('request.jwt.claims',$1,false)", [JSON.stringify({ role: "authenticated" })]);
    await db.exec("set role authenticated");
    assert.equal((await db.query("select * from realtime.messages")).rows.length, 0);
    await assert.rejects(db.exec("select public.tenh_auth_pre_request()"), /not authorized/);
    await db.exec("reset role; set role anon; select public.tenh_auth_pre_request(); reset role");
    await add(4);
    await bind(4, false, "recovery");
    await claims(4);
    await db.exec("set role authenticated");
    assert.equal((await db.query("select * from public.documents")).rows.length, 0);
    assert.equal((await db.query("select * from storage.objects")).rows.length, 0);
    assert.equal((await db.query("select * from realtime.messages")).rows.length, 0);
    await assert.rejects(db.exec("select public.tenh_auth_pre_request()"), /not authorized/);
    await db.exec("reset role");
    await add(9);
    await bind(9, false, "recovery");
    const recoveryClaims = await Promise.all(Array.from({ length: 3 }, () => value("select public.tenh_claim_recovery_session($1,$2) value", [user, sid(9)])));
    assert.equal(recoveryClaims.filter(Boolean).length, 1);
    assert.equal((await inspect(9)).status, "revoked");
    assert.equal(await value("select public.tenh_claim_recovery_session($1,$2) value", [other, sid(9)]), false);
    assert.equal(await value("select public.tenh_claim_recovery_session($1,$2) value", [user, sid(1)]), false);
    await db.query("select public.tenh_revoke_session_policies($1,$2,null)", [user, sid(1)]);
    assert.equal((await inspect(1)).status, "revoked");
    assert.equal((await bind(1, true)).status, "revoked");
    await assert.rejects(db.exec("update tenh_auth_private.session_policies set revoked_at=null"), /immutable/);
    await db.query("delete from auth.sessions where id=$1", [sid(2)]);
    assert.equal((await inspect(2)).status, "provider-session-missing");
    await add(5);
    await bind(5);
    await db.query("update auth.sessions set not_after=clock_timestamp()-interval '1 second' where id=$1", [sid(5)]);
    assert.equal((await inspect(5)).status, "provider-session-expired");
    await add(6, "2 days");
    await db.query("insert into tenh_auth_private.session_policies(session_id,user_id,authenticated_at,expires_at,remembered,kind) select id,user_id,created_at,created_at+interval '1 day',false,'normal' from auth.sessions where id=$1", [sid(6)]);
    assert.equal((await inspect(6)).status, "expired");
    await add(7, "20 days");
    assert.equal((await inspect(7)).kind, "legacy");
    await assert.rejects(db.exec("update tenh_auth_private.session_settings set enforcement_enabled=true,legacy_created_before=clock_timestamp()-interval '1 minute',legacy_grace_until=clock_timestamp()+interval '3 days'"), /check constraint/);
    await db.exec("update tenh_auth_private.session_settings set native_rollout_approval='isolated test fixture only',enforcement_enabled=true,legacy_created_before=clock_timestamp()-interval '1 minute',legacy_grace_until=clock_timestamp()+interval '3 days'");
    assert.equal((await inspect(7)).kind, "legacy");
    await add(8);
    assert.equal((await inspect(8)).status, "unbound-session");
    await db.exec("update tenh_auth_private.session_settings set legacy_created_before=clock_timestamp()-interval '2 days',legacy_grace_until=clock_timestamp()-interval '1 day'");
    assert.equal((await inspect(7)).status, "unbound-session");
    await db.query("select public.tenh_revoke_session_policies($1,null,$2)", [user, sid(8)]);
    assert.equal((await bind(8)).status, "allowed");
    await db.exec("set role service_role");
    assert.equal((await db.query("select * from public.documents")).rows.length, 2);
    await db.exec("select public.tenh_auth_pre_request(); reset role");
    const hash = "a".repeat(64);
    const attempts = await Promise.all(Array.from({ length: 8 }, (_, n) => value("select public.tenh_consume_auth_rate_limit('login',$1,$2) value", [(n + 1).toString(16).padStart(64, "0"), hash])));
    assert.equal(attempts.filter(row => row.allowed).length, 5);
    assert.ok(attempts.filter(row => !row.allowed).every(row => row.retry_after_seconds > 0));
    const ipLimited = await Promise.all(Array.from({ length: 33 }, (_, n) => value("select public.tenh_consume_auth_rate_limit('login',$1,$2) value", ["b".repeat(64), (100 + n).toString(16).padStart(64, "0")])));
    assert.equal(ipLimited.filter(row => row.allowed).length, 30);
    await db.exec("update tenh_auth_private.rate_windows set window_start=clock_timestamp()-interval '2 days',expires_at=clock_timestamp()-interval '2 days'");
    assert.equal((await value("select public.tenh_consume_auth_rate_limit('login',$1,$2) value", ["b".repeat(64), hash])).allowed, true);
    await assert.rejects(db.query("select public.tenh_consume_auth_rate_limit('login','raw-email@example.com',null)"), /opaque/);
    await db.exec("set role authenticated");
    await assert.rejects(db.query("select public.tenh_consume_auth_rate_limit('login',$1,null)", [hash]), /permission denied/);
    await db.exec("reset role");
  } finally {
    await db.close();
  }
});
